"""Deterministic mock output for the Requirements Analyst (tests and offline demos only)."""

import json
import re


def _between(text: str, tag: str):
    m = re.search(rf"<{tag}>\n(.*?)\n</{tag}>", text, re.S)
    return json.loads(m.group(1)) if m else None


def requirements_output(system: str, user: str) -> dict:
    spec = _between(user, "project_data") or {}
    previous = _between(user, "previous_requirements")
    if previous:
        content = previous
        for q in content.get("open_questions", []):
            q["blocking"] = q["blocking"] and not q.get("answer")
        return {"content": content, "summary": "[Mock] Revised requirements using the answers."}
    reqs = spec.get("requirements", {})
    functional = reqs.get("functional") or ["Users can sign in and manage their work"]
    non_functional = reqs.get("non_functional") or ["Pages load in under 2 seconds"]
    items = [
        {
            "id": f"FR-{i:03d}",
            "type": "functional",
            "title": text[:120],
            "description": text,
            "priority": "MUST",
            "acceptance_criteria": [f"Verified: {text[:200]}"],
            "source": "stated",
        }
        for i, text in enumerate(functional, 1)
    ] + [
        {
            "id": f"NFR-{i:03d}",
            "type": "non_functional",
            "title": text[:120],
            "description": text,
            "priority": "SHOULD",
            "acceptance_criteria": [],
            "source": "stated",
        }
        for i, text in enumerate(non_functional, 1)
    ]
    return {
        "content": {
            "summary": (spec.get("basics", {}).get("description") or "Project requirements")[:2000],
            "goals": spec.get("problem", {}).get("goals", [])[:30],
            "personas": [],
            "requirements": items,
            "assumptions": ["[Mock] Generated by the mock provider for testing."],
            "open_questions": [
                {
                    "id": "Q-001",
                    "question": "Who are the primary users and how many are there?",
                    "why_it_matters": "Determines scale, roles and authentication design.",
                    "blocking": True,
                    "answer": None,
                }
            ],
            "risks": [],
            "dependencies": [],
        },
        "summary": f"[Mock] Drafted {len(items)} requirements and 1 open question.",
    }


def requirements_chat_output(system: str, user: str) -> dict:
    current = _between(user, "current_requirements") or {}
    instruction = (_between_text(user, "instruction") or "").strip()
    open_ids = [
        q["id"]
        for q in current.get("open_questions", [])
        if q.get("blocking") and not q.get("answer")
    ]
    if open_ids and instruction:
        return {
            "reply": f"[Mock] Thanks — I recorded that as the answer to {open_ids[0]}.",
            "action": "answer_questions",
            "answers": {open_ids[0]: instruction},
            "instruction": None,
        }
    return {
        "reply": "[Mock] I'll revise the requirements accordingly.",
        "action": "revise",
        "answers": {},
        "instruction": instruction or None,
    }


def _between_text(text: str, tag: str) -> str | None:
    m = re.search(rf"<{tag}>\n(.*?)\n</{tag}>", text, re.S)
    return m.group(1) if m else None
