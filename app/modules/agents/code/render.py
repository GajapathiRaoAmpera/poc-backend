"""Manifest → one bash script (spec §5). Pure and deterministic; paths are pre-validated."""

import hashlib

from app.modules.agents.code.schema import CodeAgentOutput

DELIMITER = "AMPERA_EOF"


def _q(text: str) -> str:
    return "'" + text.replace("'", "'\\''") + "'"


def _delimiter(content: str) -> str:
    lines = set(content.split("\n"))
    tag, n = DELIMITER, 0
    while tag in lines:
        n += 1
        tag = f"{DELIMITER}_{n}"
    return tag


def render(content: CodeAgentOutput, sources: dict[str, int]) -> str:
    """Depends only on stored data, so the stored SHA-256 always matches the download."""
    files = sorted(content.files, key=lambda f: f.path)
    src = ", ".join(f"{k} r{v}" for k, v in sorted(sources.items()))
    out = [
        "#!/usr/bin/env bash",
        f"# Scaffold for {content.project_slug}, generated by Ampera",
        f"# Sources: {src}. Review before running. Writes files only.",
        "set -euo pipefail",
        f'target="${{1:-{content.project_slug}}}"',
        'if [ -e "$target" ] && [ -n "$(ls -A "$target" 2>/dev/null)" ]; then',
        '  echo "Refusing to write into non-empty directory: $target" >&2',
        "  exit 1",
        "fi",
        'mkdir -p "$target"',
        'cd "$target"',
    ]
    dirs = sorted({f.path.rsplit("/", 1)[0] for f in files if "/" in f.path})
    if dirs:
        out.append("mkdir -p " + " ".join(_q(d) for d in dirs))
    for f in files:
        tag = _delimiter(f.content)
        out.append(f"cat > {_q(f.path)} <<'{tag}'")
        out.append(f.content + tag)  # content is normalised to end with "\n"
    executables = [_q(f.path) for f in files if f.executable]
    if executables:
        out.append("chmod +x " + " ".join(executables))
    steps = ['"Scaffold written to $target"']
    if content.next_steps:
        steps += ["'Next steps:'"] + [_q(f"  {s}") for s in content.next_steps]
    out.append("printf '%s\\n' " + " ".join(steps))
    return "\n".join(out) + "\n"


def sha256(script: str) -> str:
    return hashlib.sha256(script.encode()).hexdigest()
